#!/usr/bin/env node
/**
 * check-shared-deps.mjs — broken-reference gate.
 *
 * THE INCIDENT: walk-evidence artifacts at clients/encore/specs_planning/_internal/ were referenced
 * in tracked files but matched .gitignore line 185 (`clients/<id>/specs_planning/`). A colleague's
 * agent stalled on arrival because those files structurally cannot reach a fresh clone.
 *
 * WHAT IT DOES:
 *   1. Reads all tracked files (git ls-files).
 *   2. Extracts path-shaped references from .md, .ts, .mjs files (@-refs, markdown links,
 *      backtick paths rooted in known repo dirs, relative ESM imports).
 *   3. Classifies each resolved path as BROKEN or FINE (see FINE_SEGMENTS/FINE_PREFIXES below).
 *   4. Reports every BROKEN hit: referencing file:line → referenced path → reason → suggested fix.
 *
 * BROKEN: the path holds authored knowledge (evidence, plans, inventories, baselines, RCA notes)
 *         a colleague cannot regenerate — it is gitignored or not tracked.
 * FINE:   the path is EXPECTED absent — credentials (.env.local), generated output (test-results/,
 *         dist/), caches (node_modules/, .auth/), per-machine runtime state.
 *
 * FALSE-POSITIVES ARE THE FAILURE MODE. A noisy checker gets muted; real traps sail through.
 * Tune FINE_SEGMENTS / FINE_PREFIXES for precision. If precision cannot reach ~95%, this checker
 * will say so honestly (see ## PRECISION in the accompanying report).
 *
 * Usage:
 *   node scripts/check-shared-deps.mjs             # report only (exits 0 always)
 *   node scripts/check-shared-deps.mjs --enforce   # exits 1 on any BROKEN hit
 *   node scripts/check-shared-deps.mjs --test-root <dir>  # override repo root (for tests)
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_REPO_ROOT = path.resolve(__dirname, '..');

// ─── FINE ALLOWLIST ──────────────────────────────────────────────────────────
// Paths matching these patterns are EXPECTED absent in a fresh clone.
// A developer creates or generates these locally — they are NOT knowledge artifacts.
// A colleague reading this file must understand WHY each entry is exempt.

/** Single path-component names: a path is FINE when any segment equals one of these. */
export const FINE_SEGMENTS = [
  '.auth',            // Playwright auth state; generated by auth.setup.ts on first local run
  'node_modules',     // npm packages; installed via npm install
  'test-results',     // Playwright test output; generated on each run
  'playwright-report',// Playwright HTML report; generated on test run
  'allure-results',   // Allure raw results; generated on test run
  'allure-report',    // Allure HTML report; generated on test run
  'html-report',      // HTML report dir; generated on test run
  'reports',          // allure/HTML report dir; created at runtime by global-setup.ts
  'dist',             // compiled JS; generated by build step
  '.build',           // build artifacts; generated by build step
  'client-delivery',  // ship package; generated by npm run client:ship
  '.browsers',        // Playwright browser binaries; installed via npx playwright install
  'ms-playwright',    // Playwright browser cache; installed via npx playwright install
  'screenshots',      // screenshot artifacts; generated during test runs
  'tmp',              // temporary dir; ephemeral files created at runtime
  'temp',             // temporary dir; ephemeral files created at runtime
  '.tmp',             // hidden temp dir; ephemeral files created at runtime
  '.recover-scratch', // recovery scratch dir; ephemeral debug artifacts
  '.work',            // agent work dir; ephemeral scratch space
  '.playwright-cli',  // MCP browser session YAMLs/PNGs; generated at runtime
  '.playwright-mcp',  // MCP browser session data; generated at runtime
  '.playwright',      // Playwright cache; generated at runtime
  'coverage',         // test coverage output; generated by coverage run
  'logs',             // log files; generated at runtime (logs/README.md IS tracked — not flagged here
                      //   because tracked files are excluded before isFine() is ever called)
];

/** Multi-segment path prefixes: a path is FINE when it starts with or contains one of these. */
export const FINE_PREFIXES = [
  '.claude/state/',            // agent runtime state (JSON/log/lock); regenerated each session
  '.claude/plans/',            // local (non-shared) plan files; per-user by design
  '.claude/private/',          // private per-user config; intentionally not shared
  '.claude/channel/',          // agent communication channel; ephemeral runtime data
  '.claude/worktrees/',        // git worktree metadata; per-machine checkout state
  '.claude/scheduled-tasks/',  // scheduled task state; runtime data
  '.claude/scheduled_tasks/',  // underscore variant of the above
  'export_test_cases/exports/',// generated export files; created by export script
];

/** Exact repo-relative paths (or path suffixes) that are always FINE. */
export const FINE_EXACT = [
  'current_plan.md',
  'rotation-state.json',
  '.claude/settings.local.json',
  'website/.claude/settings.local.json',
];

/**
 * Returns true when relPath (forward-slash, repo-relative) is in the FINE category —
 * expected absent in a fresh clone; a colleague creates or generates it locally.
 * @param {string} relPath
 */
export function isFine(relPath) {
  const p = relPath.replace(/\\/g, '/');

  // .env.local / .env.*.local at any depth (per-machine credentials)
  if (/(?:^|\/)\.env(?:\.[^/]+)?\.local$/.test(p)) return true;
  // .env.server at any depth (server credentials; never committed)
  if (/(?:^|\/)\.env\.server$/.test(p)) return true;
  // *.log files at any depth (runtime logs)
  if (/\.log$/.test(p)) return true;
  // TypeScript build artifacts
  if (p.endsWith('.tsbuildinfo')) return true;
  // Excel lock files (~$*.xlsx / ~$*.xls)
  if (/(?:^|\/)~\$/.test(p)) return true;

  // Single-segment match: any path component equal to the name
  // FINE_SEGMENTS values contain only alphanumeric, hyphens, and dots — only dots need escaping.
  for (const seg of FINE_SEGMENTS) {
    const escaped = seg.replace(/\./g, '\\.');
    if (new RegExp('(?:^|/)' + escaped + '(?:/|$)').test(p)) return true;
  }

  // Multi-segment prefix match
  for (const prefix of FINE_PREFIXES) {
    if (p === prefix.replace(/\/$/, '') || p.startsWith(prefix) || p.includes('/' + prefix)) return true;
  }

  // Exact / suffix match
  for (const exact of FINE_EXACT) {
    if (p === exact || p.endsWith('/' + exact)) return true;
  }

  return false;
}

// ─── PATH EXTRACTION ──────────────────────────────────────────────────────────

/**
 * Extracts path-shaped references from file content.
 * Returns [{rawPath, line}].
 *
 * Patterns extracted:
 *   @path/to/file        — framework @-references (auto-load convention in .md files)
 *   [text](rel/path)     — markdown relative links (not http/https/mailto)
 *   'known-dir/path'     — backtick paths rooted in a known repo directory (non-glob lines)
 *   from './rel'         — relative ESM imports in .ts/.mjs
 *
 * NOT extracted (false-positive sources):
 *   http/https URLs, mailto:, glob patterns (* or ?), email addresses (@user with no /),
 *   fragment-only links (#section), absolute paths outside the repo.
 *
 * @param {string} text
 * @param {string} relFilePath  — repo-relative path of the file being scanned
 * @returns {Array<{rawPath: string, line: number}>}
 */
export function extractPathRefs(text, relFilePath) {
  const ext = path.extname(relFilePath).toLowerCase();
  const lines = String(text ?? '').split(/\r?\n/);
  const refs = [];
  const KNOWN_DIR_RE = /^(?:clients|scripts|src|pipeline|plans|docs|\.claude|\.githooks|config)\//;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const no = i + 1;

    // Pattern 1: @-references (require at least one / to exclude @username handles)
    for (const m of line.matchAll(/@([\w.][\w.\-/]+)/g)) {
      const p = m[1];
      if (p.includes('/') && !p.includes('*') && !p.includes('?')) refs.push({ rawPath: p, line: no });
    }

    // Pattern 2: Markdown relative links [text](path) — skip URLs, fragments, globs
    if (ext === '.md') {
      for (const m of line.matchAll(/\]\(([^)]+)\)/g)) {
        const href = m[1].split('#')[0].trim();
        if (href && !href.startsWith('http') && !href.startsWith('mailto') && !href.startsWith('//') &&
            !href.includes('*') && !href.includes('?') && href.includes('/')) {
          refs.push({ rawPath: href, line: no });
        }
      }
    }

    // Pattern 3: Backtick paths rooted in a known repo dir (skip glob-containing lines)
    // Uses \x60 (backtick) in the RegExp string to avoid ESM template-literal parse confusion.
    if (!line.includes('*') && !line.includes('?')) {
      const btRe = new RegExp('\x60([\\w.][\\w.\\-/]+)\x60', 'g');
      for (const m of line.matchAll(btRe)) {
        if (KNOWN_DIR_RE.test(m[1])) refs.push({ rawPath: m[1], line: no });
      }
    }

    // Pattern 4: Relative ESM imports/requires in .ts/.mjs
    if (ext === '.ts' || ext === '.mjs') {
      for (const m of line.matchAll(/(?:from|import)\s+['"]([.][^'"]+)['"]/g)) refs.push({ rawPath: m[1], line: no });
      for (const m of line.matchAll(/require\s*\(\s*['"]([.][^'"]+)['"]\s*\)/g)) refs.push({ rawPath: m[1], line: no });
    }
  }

  return refs;
}

/**
 * Resolves a raw extracted path to a normalised repo-relative path, or null if it escapes the repo.
 * @param {string} rawPath
 * @param {string} relFilePath — repo-relative path of the file containing the reference
 * @param {string} repoRoot
 * @returns {string|null}
 */
export function resolveRef(rawPath, relFilePath, repoRoot) {
  let resolved;
  if (rawPath.startsWith('./') || rawPath.startsWith('../')) {
    resolved = path.resolve(path.join(repoRoot, path.dirname(relFilePath)), rawPath);
  } else {
    resolved = path.resolve(repoRoot, rawPath);
  }
  const rel = path.relative(repoRoot, resolved).replace(/\\/g, '/');
  return rel.startsWith('../') ? null : rel;
}

// ─── GIT HELPERS ─────────────────────────────────────────────────────────────

function getTrackedSet(repoRoot) {
  const r = spawnSync('git', ['ls-files'], { cwd: repoRoot, encoding: 'utf8', timeout: 30000 });
  if (r.error || r.status !== 0) {
    const detail = r.error ? r.error.message : (r.stderr || '').trim();
    throw new Error(
      'git ls-files failed in ' + repoRoot + ' -- cannot enumerate tracked files. Detail: ' + detail,
    );
  }
  const files = r.stdout.split('\n').map((l) => l.trim().replace(/\\/g, '/')).filter(Boolean);
  if (files.length === 0) {
    throw new Error(
      'git ls-files returned 0 tracked files in ' + repoRoot + ' -- expected a populated repository',
    );
  }
  return new Set(files);
}

/** Batch-checks which of the given repo-relative paths are gitignored. */
function batchCheckIgnore(candidates, repoRoot) {
  if (candidates.length === 0) return new Set();
  const r = spawnSync('git', ['check-ignore', '--stdin'], {
    cwd: repoRoot, encoding: 'utf8',
    input: candidates.join('\n') + '\n', timeout: 30000,
  });
  const out = r.stdout ?? '';
  return new Set(out.split('\n').map((l) => l.trim().replace(/\\/g, '/')).filter(Boolean));
}

// ─── ANALYSIS ────────────────────────────────────────────────────────────────

const SCAN_EXTS = new Set(['.md', '.ts', '.mjs']);

/** Auto-loading severity: files loaded on every Claude session are highest priority. */
function autoLoadPriority(refFile) {
  if (refFile === 'CLAUDE.md') return 0;
  if (refFile.startsWith('.claude/rules/')) return 1;
  if (refFile.startsWith('docs/read_only_docs/')) return 2;
  if (refFile.startsWith('.claude/')) return 3;
  return 10;
}

/**
 * Scans all tracked files for broken references.
 * @param {{ repoRoot: string }} opts
 * @returns {{ broken: Array, stats: object }}
 */
export function buildReport({ repoRoot }) {
  const tracked = getTrackedSet(repoRoot);
  const scannable = [...tracked].filter((f) => SCAN_EXTS.has(path.extname(f).toLowerCase()));

  // Collect candidate → [{refFile, line}] pairs (FINE and tracked paths pre-filtered)
  const candidateMap = new Map();
  for (const relFile of scannable) {
    let text;
    try { text = fs.readFileSync(path.join(repoRoot, relFile), 'utf8'); } catch { continue; }
    for (const { rawPath, line } of extractPathRefs(text, relFile)) {
      const resolved = resolveRef(rawPath, relFile, repoRoot);
      if (!resolved || resolved === relFile) continue;
      if (resolved.includes('*') || resolved.includes('?')) continue;
      if (tracked.has(resolved)) continue;   // obtainable — it's in the repo
      if (isFine(resolved)) continue;        // expected absent — no need to check
      if (!candidateMap.has(resolved)) candidateMap.set(resolved, []);
      candidateMap.get(resolved).push({ refFile: relFile, line });
    }
  }

  const candidates = [...candidateMap.keys()];
  const ignored = batchCheckIgnore(candidates, repoRoot);

  const broken = [];
  for (const relPath of candidates) {
    const isIgnored = ignored.has(relPath);
    const exists = fs.existsSync(path.join(repoRoot, relPath));
    // Flag: gitignored (structurally absent from every clone) OR untracked and missing (stale/never committed)
    // Locally-present-but-untracked paths are NOT flagged — they exist, just not yet committed.
    if (!isIgnored && exists) continue;
    const reason = isIgnored
      ? 'gitignored — structurally absent from every fresh clone'
      : 'not tracked and does not exist locally (stale or never committed)';
    const fix = isIgnored
      ? 'Track the file (remove from .gitignore), move it to a tracked location, or add it to FINE_SEGMENTS if it is expected absent.'
      : 'Commit the file or remove the stale reference.';
    for (const { refFile, line } of candidateMap.get(relPath)) {
      broken.push({ refFile, line, relPath, reason, fix, isIgnored });
    }
  }

  broken.sort((a, b) =>
    autoLoadPriority(a.refFile) - autoLoadPriority(b.refFile) ||
    a.refFile.localeCompare(b.refFile) || a.line - b.line,
  );

  return { broken, stats: { scannedFiles: scannable.length, candidates: candidates.length, broken: broken.length } };
}

// ─── CLI ─────────────────────────────────────────────────────────────────────

function parseArgs(argv) {
  const out = { repoRoot: DEFAULT_REPO_ROOT, enforce: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--enforce') { out.enforce = true; continue; }
    if (a === '--test-root') { out.repoRoot = path.resolve(argv[++i]); continue; }
    if (a === '--help' || a === '-h') { console.log('Usage: check-shared-deps.mjs [--enforce] [--test-root <dir>]'); process.exit(0); }
  }
  return out;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  let broken, stats;
  try {
    ({ broken, stats } = buildReport({ repoRoot: args.repoRoot }));
  } catch (e) {
    console.error('[check-shared-deps] FATAL -- ' + e.message);
    process.exit(1);
  }

  if (broken.length > 0) {
    console.error('\n[check-shared-deps] BROKEN references — paths a colleague cannot obtain from a fresh clone:\n');
    for (const f of broken) {
      const severity = autoLoadPriority(f.refFile) <= 2 ? '  [HIGH — auto-loading file]' : '';
      console.error('  ' + f.refFile + ':' + f.line + severity);
      console.error('    \u2192 ' + f.relPath);
      console.error('    reason: ' + f.reason);
      console.error('    fix: ' + f.fix);
      console.error('');
    }
    console.error('[check-shared-deps] ' + broken.length + ' broken reference(s) across ' + stats.scannedFiles + ' scanned files.');
  } else {
    console.log('[check-shared-deps] CLEAN \u2014 0 broken references across ' + stats.scannedFiles + ' scanned files.');
  }

  process.exit(args.enforce && broken.length > 0 ? 1 : 0);
}

const __selfPath = fileURLToPath(import.meta.url);
const __mainArg = process.argv[1] ? path.resolve(process.argv[1]) : '';
if (__mainArg === __selfPath) main();
